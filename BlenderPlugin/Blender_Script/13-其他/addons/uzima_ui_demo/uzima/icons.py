def register(name, ops):
    ICONS[name] = ops


def _bezier(p0, c, p1, n=12):
    pts = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        pts.append((u * u * p0[0] + 2 * u * t * c[0] + t * t * p1[0],
                    u * u * p0[1] + 2 * u * t * c[1] + t * t * p1[1]))
    return pts


def draw_icon(p, name, x, y, size, color, stroke):
    ops = ICONS.get(name)
    if ops is None:
        p.rect(x + size * 0.25, y + size * 0.25, size * 0.5, size * 0.5, border=color,
               border_w=stroke, radius=2)
        return
    k = size / T

    def X(u):
        return x + u * k

    def Y(v):
        return y + size - v * k

    sw = stroke
    for op in ops:
        t = op[0]
        if t == "l":
            p.line(X(op[1]), Y(op[2]), X(op[3]), Y(op[4]), sw, color)
        elif t == "p":
            p.polyline([(X(a), Y(b)) for a, b in op[1]], sw, color, closed=op[2])
        elif t == "q":
            p.polyline([(X(a), Y(b)) for a, b in _bezier(op[1], op[2], op[3])], sw, color)
        elif t == "c":
            r = op[3] * k
            p.rect(X(op[1]) - r, Y(op[2]) - r, r * 2, r * 2, radius=r, border=color, border_w=sw)
        elif t == "cf":
            r = op[3] * k
            p.circle(X(op[1]), Y(op[2]), r, fill=color)
        elif t == "r":
            p.rect(X(op[1]), Y(op[2] + op[4]), op[3] * k, op[4] * k, radius=op[5] * k,
                   border=color, border_w=sw)
        elif t == "rf":
            p.rect(X(op[1]), Y(op[2] + op[4]), op[3] * k, op[4] * k, radius=op[5] * k, fill=color)
        elif t == "a":
            # degrees clockwise on screen (y down design) -> CCW radians with y up
            d0 = op[4]
            span = op[5]
            start = -math.radians(d0 + span)
            p.arc(X(op[1]), Y(op[2]), op[3] * k, start, math.radians(span), sw, color)
        elif t == "s":
            p.sparkle(X(op[1]), Y(op[2]), op[3] * k, color)


def names():
    return sorted(ICONS)
