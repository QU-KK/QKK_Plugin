"""Vector icon set for Uzima UI.

Icons are designed on a 24 x 24 grid with y pointing down (like SVG/Tabler),
then drawn with the SDF painter so they stay sharp at any size.

Add your own:  uzima.icons.register("my_icon", [("l", 4, 4, 20, 20), ...])

Ops:
  ("l", x0, y0, x1, y1)              line
  ("p", [(x, y), ...], closed)       polyline
  ("c", cx, cy, r)                   circle outline
  ("cf", cx, cy, r)                  filled circle
  ("r", x, y, w, h, radius)          rounded rect outline
  ("rf", x, y, w, h, radius)         filled rounded rect
  ("a", cx, cy, r, deg0, span)       arc; degrees clockwise from 3 o'clock
  ("q", (x0,y0), (cx,cy), (x1,y1))   quadratic curve
  ("s", cx, cy, r)                   filled sparkle
"""

import math

T = 24.0


def _gear(teeth=8, r_out=9.4, r_in=7.0, cx=12.0, cy=12.0):
    pts = []
    step = 360.0 / teeth
    for k in range(teeth):
        a = k * step
        for da, r in ((-step * 0.36, r_in), (-step * 0.17, r_out), (step * 0.17, r_out), (step * 0.36, r_in)):
            t = math.radians(a + da)
            pts.append((cx + r * math.cos(t), cy + r * math.sin(t)))
    return pts

