_VALID_ICON_NAMES = None


def _icon_or_fallback(name: str, pre52_fallback: str = FALLBACK_ICON) -> str:
    """Return `name` if it exists in this Blender build, else a fallback.

    Some mapped icons (e.g. the 5.2 SEQ_STRIP* set) don't exist on 5.1. Callers
    that pass get_op_icon's result straight to layout.operator(icon=...) would
    crash on those builds, so we degrade here at the single source. When a
    specific `pre52_fallback` is given (a pre-5.2 icon that DOES exist), we use
    it instead of the generic DOT so older builds keep a meaningful icon.
    """
    global _VALID_ICON_NAMES
    if _VALID_ICON_NAMES is None:
        try:
            import bpy
            enum = (bpy.types.UILayout.bl_rna.functions["operator"]
                    .parameters["icon"].enum_items)
            _VALID_ICON_NAMES = {item.identifier for item in enum}
        except Exception:
            _VALID_ICON_NAMES = set()
    if not _VALID_ICON_NAMES:
        return name  # introspection unavailable — trust the name
    if name in _VALID_ICON_NAMES:
        return name
    if pre52_fallback in _VALID_ICON_NAMES:
        return pre52_fallback
    return FALLBACK_ICON


# Icons that only exist on Blender 5.2+, mapped to a pre-5.2 equivalent so older
# builds still show something meaningful instead of a blank DOT.
_NEW_ICON_FALLBACKS = {
    "SEQ_STRIP_DUPLICATE": "DUPLICATE",
    "SEQ_STRIP_MODIFIER": "MODIFIER",
    "SEQ_STRIP_DATA": "SEQ_SEQUENCER",
    "SEQ_STRIP": "SEQ_SEQUENCER",
}


def get_op_icon(op_id: str) -> str:
    """Return an icon name for ``op_id`` (BFA override, full-id, patterns, action)."""
    raw = _get_op_icon_raw(op_id)
    return _icon_or_fallback(raw, _NEW_ICON_FALLBACKS.get(raw, FALLBACK_ICON))


def _get_op_icon_raw(op_id: str) -> str:
    """Resolve the mapped icon name without version validation."""
    if not op_id:
        return FALLBACK_ICON

    try:
        from .. import HOST_APP
        is_bfa = HOST_APP == "bforartists"
    except Exception:
        is_bfa = False

    if is_bfa and op_id in BFA_FULL_ID_ICONS:
        return BFA_FULL_ID_ICONS[op_id]
    if op_id in FULL_ID_ICONS:
        return FULL_ID_ICONS[op_id]

    # Pattern rules
    if "rename" in op_id:
        return "RENAME" if is_bfa else "FILE_TEXT"
    if "select_linked_pick" in op_id or "select_linked" in op_id:
        return "LINKED"
    if op_id.endswith("_pan"):
        return "VIEW_PAN"
    # Plain click-select variants across editors
    _func = op_id.split(".", 1)[1] if "." in op_id else op_id
    if _func in ("select", "clickselect", "click_select", "select_pick",
                 "select_set", "dopesheet_select_channel"):
        return "RESTRICT_SELECT_OFF"
    # Eyedropper pickers
    if "eyedropper" in op_id:
        return "EYEDROPPER"
    # Extrude family (mesh/curve/armature + view3d edit_mesh_extrude wrappers)
    if "extrude" in op_id:
        return "FACESEL"
    # Filter / find fields
    if _func in ("start_filter", "list_start_filter", "view_start_filter",
                 "clear_filter", "start_find"):
        return "FILTER"
    if op_id.endswith("_hide") or op_id in _HIDE_EXTRA:
        return "HIDE_ON"
    if op_id.endswith("_reveal") or op_id in _REVEAL_EXTRA:
        return "HIDE_OFF"

    action = op_id.split(".", 1)[1] if "." in op_id else op_id
    return ACTION_ICONS.get(action, FALLBACK_ICON)

