"""Operator -> icon lookup for the simplified panel.

Two layers, checked in order:
  1. ``FULL_ID_ICONS``  — exact operator id (e.g. ``wm.call_menu_pie``)
  2. ``ACTION_ICONS``   — the action suffix after the dot (e.g. ``select_all``)

Most Blender operators share an action suffix across contexts
(``mesh.select_all``, ``object.select_all``, ``curve.select_all`` …), so
keying on the suffix means an entry that binds 30 ``*.select_all`` operators
collapses to a single icon. Anything unmatched falls back to ``FALLBACK_ICON``.

These are intentionally simple to edit — add or change entries freely. Icon
names are validated at draw time, so an unknown name degrades to the fallback
rather than crashing the panel.
"""

